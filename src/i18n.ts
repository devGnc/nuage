const dicts: Record<Lang, Dict> = { fr, en }

export function translate(lang: Lang, key: TKey, params?: Record<string, string | number>): string {
  let s = dicts[lang][key] ?? fr[key] ?? key
  if (params) for (const [k, v] of Object.entries(params)) s = s.replace(`{${k}}`, String(v))
  return s
}

export function useT() {
  const lang = useSettings((s) => s.lang)
  return (key: TKey, params?: Record<string, string | number>) => translate(lang, key, params)
}

export function t(key: TKey, params?: Record<string, string | number>) {
  return translate(useSettings.getState().lang, key, params)
}

export function useLang(): Lang {
  return useSettings((s) => s.lang)
}
